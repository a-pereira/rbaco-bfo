"""Write rdfs:label comments into RBO's Turtle, or check that they are current.

Usage: annotate_ttl.py <rbo-dir> [--check]

Files: rbo.ttl, rbo-domain.ttl, data/*.ttl and data/derived/*.ttl. build_data.py and run_queries.py call
annotate_file on each data file they write, so regenerated data keeps its comments. In the data, the
individuals' own IRIs are readable and carry no comment; the classes and properties they use do.

RBO's IRIs are opaque (RBO_0000113, cco:ont00001808), so each term block gets a header line naming its
label, and each line that names a labeled IRI outside the subject position gets a trailing comment with
the labels in the order the IRIs appear:

    #: rbo:RBO_0000113  cites regulation
    rbo:RBO_0000113 rdf:type owl:ObjectProperty ;
        rdfs:subPropertyOf cco:ont00001808 ;                #: is about

Labels come from rbo.ttl, rbo-domain.ttl and imports/*.ttl, never from the data. W3C, Dublin Core and SKOS terms are not
annotated. The tool owns every comment beginning "#:" and nothing else: it removes them and writes them
afresh, so a second run changes nothing, and banners and hand-written comments are kept. A comment is not
part of the graph, and before writing, the tool checks that the new text parses to a graph isomorphic to
the old one.

--check writes nothing and exits 1 if any file differs from what the tool would write: a label that
changed, a term added without a comment, or a comment edited by hand. rdflib and other serializers drop
comments, so a file regenerated by a tool loses them and fails the check until the tool is rerun.
"""
import glob
import os
import re
import sys

from rdflib import Graph, Literal, URIRef
from rdflib.namespace import RDFS

FILES = ["rbo.ttl", "rbo-domain.ttl"]
SKIP_NS = ("http://www.w3.org/", "http://purl.org/dc/", "http://www.w3.org/2004/02/skos/")
MARK = "#:"
COLUMN = 56
PNAME = re.compile(r"([A-Za-z][\w-]*)?:([A-Za-z0-9_](?:[\w.-]*[\w-])?)")


def load_labels(rdir):
    g = Graph()
    for f in [os.path.join(rdir, n) for n in FILES] + sorted(glob.glob(os.path.join(rdir, "imports", "*.ttl"))):
        g.parse(f, format="turtle")
    labels = {}
    for s, o in g.subject_objects(RDFS.label):
        if not isinstance(s, URIRef) or not isinstance(o, Literal):
            continue
        rank = 0 if o.language == "en" else (1 if o.language is None else 2)
        text = " ".join(str(o).split())
        if s not in labels or (rank, text) < labels[s]:
            labels[s] = (rank, text)
    return {s: t for s, (_, t) in labels.items()}


def scan(line):
    """Return (tokens, comment_start) for one line. tokens are (start, text, iri-or-pname) found outside
    string literals and comments; comment_start is the index of the comment's '#', or None."""
    tokens, i, n = [], 0, len(line)
    while i < n:
        c = line[i]
        if c in "\"'":
            if line.startswith(c * 3, i):
                raise ValueError("long string literals are not supported")
            i += 1
            while i < n and line[i] != c:
                i += 2 if line[i] == "\\" else 1
            i += 1
        elif c == "<":
            j = line.index(">", i)
            tokens.append((i, line[i:j + 1], ("iri", line[i + 1:j])))
            i = j + 1
        elif c == "#":
            return tokens, i
        elif c == "@":
            m = re.match(r"@[\w-]+", line[i:])
            i += len(m.group(0)) if m else 1
        else:
            m = PNAME.match(line, i)
            if m and (i == 0 or not (line[i - 1].isalnum() or line[i - 1] in "_-")):
                tokens.append((i, m.group(0), ("pname", m.group(1) or "", m.group(2))))
                i = m.end()
            else:
                i += 1
    return tokens, None


def annotate(text, labels):
    prefixes = dict(re.findall(r"^@prefix\s+([\w-]*):\s*<([^>]+)>", text, re.M))

    def resolve(tok):
        if tok[0] == "iri":
            return URIRef(tok[1])
        ns = prefixes.get(tok[1])
        return URIRef(ns + tok[2]) if ns else None

    def label_of(tok):
        iri = resolve(tok)
        if iri is None or str(iri).startswith(SKIP_NS):
            return None
        return labels.get(iri)

    out = []
    for line in text.split("\n"):
        if line.lstrip().startswith(MARK):
            continue                                    # a header this tool wrote
        tokens, cstart = scan(line)
        if cstart is not None and line[cstart:].startswith(MARK):
            line, cstart = line[:cstart].rstrip(), None  # a trailing comment this tool wrote
        if line.startswith(("@prefix", "PREFIX")) or not tokens:
            out.append(line)
            continue
        subject = tokens[0] if tokens[0][0] == 0 else None
        if subject:
            lab = label_of(subject[2])
            if lab:
                out.append(f"{MARK} {subject[1]}  {lab}")
        if cstart is None:
            seen, labs = set(), []
            for tok in tokens:
                if tok is subject or tok[1] in seen:
                    continue
                seen.add(tok[1])
                lab = label_of(tok[2])
                if lab:
                    labs.append(lab)
            if labs:
                line = line.ljust(COLUMN - 1) + " " if len(line) < COLUMN - 1 else line + "  "
                line += f"{MARK} " + " | ".join(labs)
        out.append(line)
    return "\n".join(out)


def same_graph(a, b):
    ga, gb = Graph(), Graph()
    ga.parse(data=a, format="turtle")
    gb.parse(data=b, format="turtle")
    return ga.isomorphic(gb)


def annotate_file(path, labels, check=False):
    """Annotate one file in place, or with check=True only compare. Returns (status, headers, trailing),
    status being "current", "written" or "stale"."""
    with open(path, encoding="utf-8", newline="") as fh:
        old = fh.read()
    eol = "\r\n" if "\r\n" in old else "\n"
    new = annotate(old.replace("\r\n", "\n"), labels).replace("\n", eol)
    if not same_graph(old, new):
        raise ValueError(f"{path}: the annotated text parses to a different graph; nothing written")
    lines = new.split(eol)
    headers = sum(1 for ln in lines if ln.startswith(MARK))
    trailing = sum(1 for ln in lines if not ln.startswith(MARK) and f" {MARK} " in ln)
    if new == old:
        return "current", headers, trailing
    if check:
        return "stale", headers, trailing
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(new)
    return "written", headers, trailing


def targets(rdir):
    """The ontology's own Turtle, then the datasets and the derived files."""
    return ([os.path.join(rdir, n) for n in FILES] + sorted(glob.glob(os.path.join(rdir, "data", "*.ttl")))
            + sorted(glob.glob(os.path.join(rdir, "data", "derived", "*.ttl"))))


def main():
    rdir, check = sys.argv[1], "--check" in sys.argv[2:]
    labels = load_labels(rdir)
    stale = 0
    for path in targets(rdir):
        name = os.path.relpath(path, rdir).replace("\\", "/")
        status, headers, trailing = annotate_file(path, labels, check)
        stale += status == "stale"
        print(f"{name}: {status.upper() if status == 'stale' else status} "
              f"({headers} headers, {trailing} trailing comments)")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
