"""Build imports/iao-extract.ttl from a full copy of iao.owl.

Usage: build_iao_extract.py <iao.owl> <bfo-core.ttl> <out.ttl>

Keeps, for each listed IAO term: its declaration, rdfs:label, IAO definition (IAO_0000115),
rdfs:domain / rdfs:range, and every rdfs:subClassOf axiom whose signature lies inside the
listed terms plus BFO 2020 core. Every axiom dropped for falling outside that signature is
printed, so the omission is on record.
"""
import sys
from rdflib import Graph, URIRef, BNode, Literal, Namespace, RDF, RDFS, OWL
from rdflib.namespace import DCTERMS

OBO = Namespace("http://purl.obolibrary.org/obo/")
TERMS = ["IAO_0000030", "IAO_0000033", "IAO_0000104", "IAO_0000010", "IAO_0000136"]
DEF = OBO.IAO_0000115

iao_path, bfo_path, out_path = sys.argv[1:4]
iao = Graph(); iao.parse(iao_path, format="xml")
bfo = Graph(); bfo.parse(bfo_path, format="turtle")
bfo_sig = {s for s in bfo.subjects() if isinstance(s, URIRef)}
keep = {OBO[t] for t in TERMS}
allowed = keep | bfo_sig | {OWL.Thing}


def signature(g, node, seen=None):
    """Named entities mentioned in an anonymous class expression."""
    seen = seen or set()
    if isinstance(node, URIRef):
        return {node}
    if node in seen:
        return set()
    seen.add(node)
    sig = set()
    for p, o in g.predicate_objects(node):
        if p == RDF.type:
            continue
        if p in (OWL.onProperty, OWL.someValuesFrom, OWL.allValuesFrom, OWL.onClass, OWL.hasValue):
            sig |= signature(g, o, seen)
        elif p in (RDF.first, RDF.rest, OWL.intersectionOf, OWL.unionOf, OWL.complementOf):
            sig |= signature(g, o, seen)
    sig.discard(RDF.nil)
    return sig


def copy_expr(src, dst, node):
    if isinstance(node, URIRef):
        return node
    new = BNode()
    for p, o in src.predicate_objects(node):
        dst.add((new, p, copy_expr(src, dst, o) if isinstance(o, BNode) else o))
    return new


out = Graph()
out.bind("obo", OBO); out.bind("owl", OWL); out.bind("dcterms", DCTERMS)
onto = URIRef("https://example.org/rbac-bfo/imports/iao-extract.owl")
out.add((onto, RDF.type, OWL.Ontology))
out.add((onto, DCTERMS.source, URIRef("http://purl.obolibrary.org/obo/iao/2026-03-30/iao.owl")))
out.add((onto, DCTERMS.license, URIRef("http://creativecommons.org/licenses/by/4.0/")))
out.add((onto, RDFS.comment, Literal(
    "Extract of IAO version 2026-03-30 for RBO: the terms RBO uses, their labels and definitions, "
    "domains and ranges, and the subclass axioms whose signature lies within these terms and BFO 2020 "
    "core. Generated by tools/build_iao_extract.py; do not edit by hand.", lang="en")))
out.add((DEF, RDF.type, OWL.AnnotationProperty))
out.add((DEF, RDFS.label, Literal("definition", lang="en")))

dropped = []
for t in sorted(keep):
    for typ in iao.objects(t, RDF.type):
        out.add((t, RDF.type, typ))
    for p in (RDFS.label, DEF):
        for o in iao.objects(t, p):
            out.add((t, p, o))
    for p in (RDFS.domain, RDFS.range, RDFS.subPropertyOf, RDFS.subClassOf):
        for o in iao.objects(t, p):
            sig = signature(iao, o)
            if sig <= allowed:
                out.add((t, p, copy_expr(iao, out, o)))
            else:
                dropped.append((t, p, sorted(str(x) for x in sig - allowed)))

out.serialize(out_path, format="turtle")
print(f"wrote {out_path}: {len(out)} triples, {len(keep)} terms")
for t, p, why in dropped:
    print(f"DROPPED {t.split('/')[-1]} {p.split('#')[-1]} -- outside signature: {', '.join(w.split('/')[-1] for w in why)}")
